public class LodHelper extends org.citydb.database.util.LodHelper {

    protected LodHelper(DatabaseAdapter adapter) {
        super(adapter);
    }

    @Override
    public Select getBottomUpQuery(Set<String> lods) {
        List<Object> args = new ArrayList<>();
        String lodCondition;
        if (lods.isEmpty()) {
            lodCondition = "prop.val_lod is not null";
        } else {
            lodCondition = "prop.val_lod in (" + String.join(", ", Collections.nCopies(lods.size(), "{}")) + ")";
            lods.stream().map(StringLiteral::of).forEach(args::add);
        }

        args.add(RelationType.CONTAINS.getDatabaseValue());

        // starts at the geometry properties with the given LoDs and walks up to the features containing them;
        // connect by returns a feature once per path, so the ids are made distinct
        String hierarchySql = "select distinct prop.feature_id as id from " + getPropertyTable() + " prop " +
                "start with (prop.val_geometry_id is not null or prop.val_implicitgeom_id is not null) " +
                "and " + lodCondition + " " +
                "connect by nocycle prior prop.feature_id = prop.val_feature_id " +
                "and prop.val_relation_type = {}";

        Table hierarchy = Table.of(Function.of("", PlainSql.of(hierarchySql, args.toArray())));
        return Select.newInstance()
                .select(hierarchy.column("id"))
                .from(hierarchy);
    }

    @Override
    public Select getTopDownQuery(Set<String> lods, Table table) {
        Table property = Table.of(
                SchemaAdapter.enquoteSqlName(org.citydb.database.schema.Table.PROPERTY.getName()),
                SchemaAdapter.enquoteSqlName(adapter.getConnectionDetails().getSchema()));

        // Oracle does not allow a recursive CTE to reference the outer query, so the feature hierarchy is
        // walked with connect by instead. The alias "prop" cannot clash with the single-letter aliases
        // generated by sqlbuilder for the surrounding query.
        String hierarchySql = "select {} as id from dual " +
                "union all " +
                "select prop.val_feature_id from " + getPropertyTable() + " prop " +
                "start with prop.feature_id = {} and prop.val_feature_id is not null " +
                "and prop.val_relation_type = {} " +
                "connect by nocycle prior prop.val_feature_id = prop.feature_id " +
                "and prop.val_feature_id is not null and prop.val_relation_type = {}";

        // joining the hierarchy as inline view is ~15x faster than an in-subquery; sqlbuilder has no
        // Table.of(PlainSql) yet, so an unnamed function is used to render the plain SQL in parentheses
        Table hierarchy = Table.of(Function.of("", PlainSql.of(hierarchySql,
                table.column("id"), table.column("id"),
                RelationType.CONTAINS.getDatabaseValue(), RelationType.CONTAINS.getDatabaseValue())));

        return Select.newInstance()
                .select(IntegerLiteral.of(1))
                .from(property)
                .join(hierarchy).on(hierarchy.column("id").eq(property.column("feature_id")))
                .where(property.column("val_geometry_id").isNotNull()
                                .or(property.column("val_implicitgeom_id").isNotNull()),
                        getLodCondition(property, lods))
                .fetch(1);
    }

    private BooleanExpression getLodCondition(Table property, Set<String> lods) {
        return lods.isEmpty()
                ? property.column("val_lod").isNotNull()
                : adapter.getSchemaAdapter().getOperationHelper()
                .in(property.column("val_lod"), lods.stream().map(StringLiteral::of).toList());
    }

    private String getPropertyTable() {
        return SchemaAdapter.qualify(adapter.getConnectionDetails().getSchema(),
                org.citydb.database.schema.Table.PROPERTY.getName());
    }

    @Override
    public long getSearchThreshold() {
        return 50000;
    }

    @Override
    public Optional<LodStatistics> getStatistics(Connection connection) throws SQLException {
        String owner = adapter.getConnectionDetails().getSchema().toUpperCase(Locale.ROOT);
        String table = org.citydb.database.schema.Table.PROPERTY.getName().toUpperCase(Locale.ROOT);

        long rows;
        long nulls;
        boolean stale;
        boolean hasHistogram;
        String sql = "select t.num_rows, t.stale_stats, c.num_nulls, c.num_distinct, c.histogram " +
                "from all_tab_statistics t " +
                "join all_tab_col_statistics c on c.owner = t.owner and c.table_name = t.table_name " +
                "where t.owner = ? and t.table_name = ? and t.object_type = 'TABLE' and c.column_name = 'VAL_LOD'";

        try (PreparedStatement stmt = connection.prepareStatement(sql)) {
            stmt.setString(1, owner);
            stmt.setString(2, table);
            try (ResultSet rs = stmt.executeQuery()) {
                if (!rs.next() || rs.getObject(1) == null) {
                    // no statistics, e.g. because the table has not been analyzed yet
                    return Optional.empty();
                }

                rows = rs.getLong(1);
                stale = !"NO".equals(rs.getString(2));
                nulls = rs.getLong(3);
                // only a frequency histogram lists all LoDs, the other types may omit frequent values
                hasHistogram = "FREQUENCY".equals(rs.getString(5));
                if (!hasHistogram && rs.getLong(4) > 0) {
                    return Optional.empty();
                }
            }
        }

        double nullFraction = rows > 0 ? (double) nulls / rows : 1;
        Map<String, Double> frequencies = new HashMap<>();
        if (hasHistogram) {
            // the endpoint numbers are cumulative counts of the rows with LoD
            sql = "select endpoint_actual_value, endpoint_value, endpoint_number from all_tab_histograms " +
                    "where owner = ? and table_name = ? and column_name = 'VAL_LOD' " +
                    "order by endpoint_number";

            Map<String, Long> counts = new HashMap<>();
            long total = 0;
            try (PreparedStatement stmt = connection.prepareStatement(sql)) {
                stmt.setString(1, owner);
                stmt.setString(2, table);
                try (ResultSet rs = stmt.executeQuery()) {
                    while (rs.next()) {
                        String lod = rs.getString(1);
                        if (lod == null) {
                            lod = decodeEndpointValue(rs.getBigDecimal(2));
                            if (lod == null) {
                                return Optional.empty();
                            }
                        }

                        counts.merge(lod, rs.getLong(3) - total, Long::sum);
                        total = rs.getLong(3);
                    }
                }
            }

            if (total == 0) {
                return Optional.empty();
            }

            for (Map.Entry<String, Long> entry : counts.entrySet()) {
                frequencies.put(entry.getKey(), (1 - nullFraction) * entry.getValue() / total);
            }
        }

        return Optional.of(LodStatistics.of(frequencies, nullFraction, rows, stale));
    }

    private String decodeEndpointValue(BigDecimal value) {
        if (value == null) {
            return null;
        }

        // Oracle stores the first 15 bytes of a string as a number rounded to 15 significant digits, which
        // keeps only the first 6 bytes exact
        long bytes = value.toBigInteger()
                .add(BigInteger.ONE.shiftLeft(71))
                .shiftRight(72)
                .longValue();

        StringBuilder lod = new StringBuilder();
        boolean terminated = false;
        for (int i = 5; i >= 0; i--) {
            int current = (int) (bytes >> (8 * i)) & 0xff;
            if (current == 0) {
                terminated = true;
            } else if (terminated || current > 0x7f) {
                return null;
            } else {
                lod.append((char) current);
            }
        }

        // without a terminating zero byte, the value may be longer than the bytes that could be decoded
        return terminated ? lod.toString() : null;
    }
}
